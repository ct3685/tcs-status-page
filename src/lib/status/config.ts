type ServiceSeed = Partial<ServiceConfig> &
  Pick<ServiceConfig, 'slug' | 'name' | 'feedType' | 'criticality' | 'order'>;

function service(input: ServiceSeed): ServiceConfig {
  return {
    id: input.slug,
    enabled: true,
    hidden: false,
    pinned: false,
    tags: [],
    ignoreTitlePatterns: [],
    maintenanceKeywords: [],
    incidentKeywords: [],
    noIncidentPatterns: [],
    ...input,
  };
}

